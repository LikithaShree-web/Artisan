const mongoose=require('mongoose');

const data=mongoose.Schema({
    name:{
        type:String,
        required:true
    },
    phone:{
        type:String,
        required:true
    },
    email:{
        type:String,
        required:true
    },
    password:{
        type:String,
        required:true
    }
});

const model=mongoose.model("Artisan",data); 

module.exports=model;